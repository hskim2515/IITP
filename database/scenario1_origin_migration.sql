-- scenario1 로컬 좌표 원점 갱신
--
-- 배경: network.xml이 표준 노드링크 데이터로 교체되면서 로컬 좌표 원점이 변경됨
--   구 좌표계: 노드 center 값이 약 (1800, 1300) 범위
--   신 좌표계: 노드 center 값이 약 (0~80, -300~-100) 범위
--
-- 오프셋 측정 (노드 3개 검증):
--   Δx = -1788.8784 m (동쪽으로 1788.88 m 이동)
--   Δy = -1458.1595 m (북쪽으로 1458.16 m 이동)
--
-- 수정 공식:
--   new_longitude = old_longitude + 1788.8784 / 88000  (≈ +0.020328)
--   new_latitude  = old_latitude  + 1458.1595 / 111000 (≈ +0.013137)

UPDATE scenario
SET longitude = 126.7325 + (1788.8784 / 88000.0),  -- ≈ 126.752828
    latitude  = 37.4928  + (1458.1595 / 111000.0)   -- ≈ 37.505937
WHERE key = 'scenario1';
